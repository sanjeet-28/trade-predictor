"""Foundational domain models for the Forex Trade Detection System.

Defines standardized data structures for bounding boxes, frames,
detector events, trade states, and persistent trade records.
"""

from __future__ import annotations

import math
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, Optional, Tuple


class DetectorType(str, Enum):
    """Identifies which detection mechanism triggered an event."""
    LABEL = "LABEL_DETECTOR"   # Detector A: BUY/SELL text badge
    BOX = "BOX_DETECTOR"       # Detector B: Position box (green/red rect + entry line)


class TradeSignalType(str, Enum):
    """Classification of signal direction (stored internally, never sent to Telegram)."""
    BUY = "BUY"
    SELL = "SELL"
    UNKNOWN = "UNKNOWN"


class TradeState(str, Enum):
    """Lifecycle status of a detected trade."""
    BASELINE = "BASELINE"   # Present at boot/calibration; notification suppressed
    ACTIVE = "ACTIVE"       # Active trade currently monitored on chart
    CLOSED = "CLOSED"       # Trade removed, hit SL/TP, or dismissed


class NotificationStatus(str, Enum):
    """Lifecycle status of a Telegram notification."""
    PENDING = "PENDING"     # Queued in outbox, awaiting delivery attempt
    SENDING = "SENDING"     # In-flight delivery attempt
    SENT = "SENT"           # Confirmed delivered by Telegram API
    FAILED = "FAILED"       # Failed permanently or exhausted max retries


@dataclass(frozen=True)
class BoundingBox:
    """Represents a 2D bounding rectangle in pixel coordinates."""
    x: int
    y: int
    width: int
    height: int

    def __post_init__(self) -> None:
        if self.width < 0 or self.height < 0:
            raise ValueError(f"Width and height must be non-negative: w={self.width}, h={self.height}")

    @property
    def x2(self) -> int:
        """Right edge coordinate."""
        return self.x + self.width

    @property
    def y2(self) -> int:
        """Bottom edge coordinate."""
        return self.y + self.height

    @property
    def area(self) -> int:
        """Area in square pixels."""
        return self.width * self.height

    @property
    def centroid(self) -> Tuple[float, float]:
        """Center point (cx, cy) of the bounding box."""
        return (self.x + self.width / 2.0, self.y + self.height / 2.0)

    def contains_point(self, px: float, py: float) -> bool:
        """Check if point (px, py) lies within this bounding box."""
        return self.x <= px <= self.x2 and self.y <= py <= self.y2

    def distance_to(self, other: BoundingBox) -> float:
        """Euclidean distance between centroids."""
        cx1, cy1 = self.centroid
        cx2, cy2 = other.centroid
        return math.hypot(cx2 - cx1, cy2 - cy1)

    def iou(self, other: BoundingBox) -> float:
        """Calculate Intersection-over-Union (IoU) with another bounding box."""
        ix1 = max(self.x, other.x)
        iy1 = max(self.y, other.y)
        ix2 = min(self.x2, other.x2)
        iy2 = min(self.y2, other.y2)

        intersection_w = max(0, ix2 - ix1)
        intersection_h = max(0, iy2 - iy1)
        intersection_area = intersection_w * intersection_h

        if intersection_area == 0:
            return 0.0

        union_area = self.area + other.area - intersection_area
        if union_area <= 0:
            return 0.0

        return float(intersection_area) / float(union_area)

    def to_dict(self) -> Dict[str, int]:
        """Serialize bounding box to dictionary."""
        return {"x": self.x, "y": self.y, "width": self.width, "height": self.height}

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> BoundingBox:
        """Deserialize bounding box from dictionary."""
        return cls(
            x=int(data["x"]),
            y=int(data["y"]),
            width=int(data["width"]),
            height=int(data["height"]),
        )


@dataclass
class Frame:
    """Represents a single video frame ingested from the livestream."""
    frame_id: int
    timestamp: datetime
    width: int
    height: int
    data: Optional[Any] = None  # NumPy array (BGR) when image processing, or None in tests


@dataclass
class DetectionEvent:
    """Represents a raw detection event generated by Detector A or Detector B."""
    event_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    detector_type: DetectorType = DetectorType.LABEL
    signal_type: TradeSignalType = TradeSignalType.UNKNOWN
    confidence: float = 1.0
    bbox: BoundingBox = field(default_factory=lambda: BoundingBox(0, 0, 0, 0))
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    snapshot_path: Optional[str] = None
    raw_metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        """Serialize detection event to dictionary."""
        return {
            "event_id": self.event_id,
            "detector_type": self.detector_type.value,
            "signal_type": self.signal_type.value,
            "confidence": self.confidence,
            "bbox": self.bbox.to_dict(),
            "timestamp": self.timestamp.isoformat(),
            "snapshot_path": self.snapshot_path,
            "raw_metadata": self.raw_metadata,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> DetectionEvent:
        """Deserialize detection event from dictionary."""
        return cls(
            event_id=data["event_id"],
            detector_type=DetectorType(data["detector_type"]),
            signal_type=TradeSignalType(data["signal_type"]),
            confidence=float(data["confidence"]),
            bbox=BoundingBox.from_dict(data["bbox"]),
            timestamp=datetime.fromisoformat(data["timestamp"]),
            snapshot_path=data.get("snapshot_path"),
            raw_metadata=data.get("raw_metadata", {}),
        )


@dataclass
class TradeRecord:
    """Represents a validated trade tracked across frames by the Central Event Manager."""
    trade_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    state: TradeState = TradeState.ACTIVE
    detector_source: DetectorType = DetectorType.LABEL
    first_detected_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    last_seen_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    bbox: BoundingBox = field(default_factory=lambda: BoundingBox(0, 0, 0, 0))
    notification_sent: bool = False
    notification_sent_at: Optional[datetime] = None
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        """Serialize trade record to dictionary."""
        return {
            "trade_id": self.trade_id,
            "state": self.state.value,
            "detector_source": self.detector_source.value,
            "first_detected_at": self.first_detected_at.isoformat(),
            "last_seen_at": self.last_seen_at.isoformat(),
            "bbox": self.bbox.to_dict(),
            "notification_sent": self.notification_sent,
            "notification_sent_at": (
                self.notification_sent_at.isoformat() if self.notification_sent_at else None
            ),
            "metadata": self.metadata,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> TradeRecord:
        """Deserialize trade record from dictionary."""
        return cls(
            trade_id=data["trade_id"],
            state=TradeState(data["state"]),
            detector_source=DetectorType(data["detector_source"]),
            first_detected_at=datetime.fromisoformat(data["first_detected_at"]),
            last_seen_at=datetime.fromisoformat(data["last_seen_at"]),
            bbox=BoundingBox.from_dict(data["bbox"]),
            notification_sent=bool(data.get("notification_sent", False)),
            notification_sent_at=(
                datetime.fromisoformat(data["notification_sent_at"])
                if data.get("notification_sent_at")
                else None
            ),
            metadata=data.get("metadata", {}),
        )


@dataclass
class NotificationRecord:
    """Represents a persistent notification outbox entry."""
    notification_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    trade_id: str = ""
    chat_id: str = ""
    message_text: str = "TRADE IS ACTIVE!"
    photo_path: Optional[str] = None
    status: NotificationStatus = NotificationStatus.PENDING
    retry_count: int = 0
    max_retries: int = 5
    next_retry_at: Optional[datetime] = None
    last_error: Optional[str] = None
    created_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    sent_at: Optional[datetime] = None

    def to_dict(self) -> Dict[str, Any]:
        """Serialize notification record to dictionary."""
        return {
            "notification_id": self.notification_id,
            "trade_id": self.trade_id,
            "chat_id": self.chat_id,
            "message_text": self.message_text,
            "photo_path": self.photo_path,
            "status": self.status.value,
            "retry_count": self.retry_count,
            "max_retries": self.max_retries,
            "next_retry_at": self.next_retry_at.isoformat() if self.next_retry_at else None,
            "last_error": self.last_error,
            "created_at": self.created_at.isoformat(),
            "updated_at": self.updated_at.isoformat(),
            "sent_at": self.sent_at.isoformat() if self.sent_at else None,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> NotificationRecord:
        """Deserialize notification record from dictionary."""
        return cls(
            notification_id=data["notification_id"],
            trade_id=data["trade_id"],
            chat_id=data["chat_id"],
            message_text=data["message_text"],
            photo_path=data.get("photo_path"),
            status=NotificationStatus(data["status"]),
            retry_count=int(data.get("retry_count", 0)),
            max_retries=int(data.get("max_retries", 5)),
            next_retry_at=(
                datetime.fromisoformat(data["next_retry_at"])
                if data.get("next_retry_at")
                else None
            ),
            last_error=data.get("last_error"),
            created_at=datetime.fromisoformat(data["created_at"]),
            updated_at=datetime.fromisoformat(data["updated_at"]),
            sent_at=(
                datetime.fromisoformat(data["sent_at"])
                if data.get("sent_at")
                else None
            ),
        )

